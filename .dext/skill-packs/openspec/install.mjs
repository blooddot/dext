// Regenerates the six Skills this pack owns, straight from the OpenSpec CLI.
// Rerun after `npm i -g @fission-ai/openspec` upgrades it, then reload the window.
//
// usage: node .dext/skill-packs/openspec/install.mjs

import { spawnSync } from "node:child_process";
import { existsSync, mkdirSync, mkdtempSync, readFileSync, readdirSync, rmSync, writeFileSync } from "node:fs";
import { tmpdir } from "node:os";
import { join } from "node:path";

const CLI = "openspec";
const packRoot = import.meta.dirname;
const dext = join(packRoot, "..", "..");
const skillsRoot = join(dext, "skills");

const work = mkdtempSync(join(tmpdir(), "dext-openspec-"));
try {
  const run = spawnSync(CLI, ["init", "--tools", "codex"], {
    cwd: work,
    shell: true,
    stdio: ["ignore", "pipe", "pipe"],
    env: { ...process.env, OPENSPEC_TELEMETRY: "0" }
  });
  if (run.status !== 0) {
    console.error(`${CLI} init failed:\n${run.stderr?.toString() || run.stdout?.toString() || ""}`.trim());
    process.exit(run.status ?? 1);
  }

  // `--tools codex` is what makes the CLI write the shared `.agents/skills`
  // copy instead of a host-specific one; `none` writes no Skills at all.
  const generated = join(work, ".agents", "skills");
  if (!existsSync(generated)) {
    console.error(`${CLI} init wrote no .agents/skills, so there is nothing to install.`);
    process.exit(1);
  }

  const records = [];
  for (const id of readdirSync(generated).sort()) {
    const source = join(generated, id, "SKILL.md");
    if (!existsSync(source)) continue;
    const text = readFileSync(source, "utf8");
    mkdirSync(join(skillsRoot, id), { recursive: true });
    writeFileSync(join(skillsRoot, id, "SKILL.md"), text);
    records.push({ id, description: frontMatter(text, "description") ?? "", directory: `.agents/skills/${id}` });
  }
  if (!records.length) {
    console.error(`${CLI} init produced no SKILL.md.`);
    process.exit(1);
  }

  // No `source`: the GitHub update button must not appear, because the only way
  // to refresh these is to rerun this script.
  const manifest = {
    name: "openspec",
    notes: ["Generated by `node .dext/skill-packs/openspec/install.mjs`; rerun it after upgrading the openspec CLI."],
    skills: records.map(({ id, description, directory }) => ({
      id, name: id, description, directory, commands: [], warnings: []
    })),
    commands: []
  };
  writeFileSync(join(packRoot, "pack.json"), `${JSON.stringify(manifest, null, 2)}\n`);

  console.log(`${records.length} Skills → .dext/skills/, grouped as pack 'openspec'.`);
  console.log("Reload the window to see them in Resources.");
} finally {
  rmSync(work, { recursive: true, force: true });
}

/** `name: x` and `description: y` are single-line in every generated Skill. */
function frontMatter(text, key) {
  const block = /^---\r?\n([\s\S]*?)\r?\n---/.exec(text)?.[1];
  const line = block && new RegExp(`^${key}:\\s*(.+)$`, "m").exec(block)?.[1];
  return line?.replace(/^["']|["']$/g, "").trim();
}
